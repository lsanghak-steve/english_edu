/**
 * 학습 레벨 (초등단어, 중등단어, 고등단어) 6개 국어 번역 헬퍼
 */
export function translateGradeLevel(gradeStr, lang = 'ko') {
  if (!gradeStr) return t('grade_mid', lang);
  const clean = String(gradeStr).trim();
  if (clean.includes('초등') || clean.toLowerCase().includes('elementary') || clean.includes('小学') || clean.includes('Primaire') || clean.includes('小学生') || clean.includes('Tiểu học') || clean.includes('प्राथमिक')) {
    return t('grade_elem', lang);
  }
  if (clean.includes('중등') || clean.toLowerCase().includes('middle') || clean.includes('初中') || clean.includes('Collège') || clean.includes('中学生') || clean.includes('Trung học cơ sở') || clean.includes('माध्यमिक')) {
    return t('grade_mid', lang);
  }
  if (clean.includes('고등') || clean.includes('수능') || clean.toLowerCase().includes('high') || clean.includes('高中') || clean.includes('Lycée') || clean.includes('高校生') || clean.includes('Trung học phổ thông') || clean.includes('उच्चतर')) {
    return t('grade_high', lang);
  }
  return gradeStr;
}

